// Loops
// A loop is used to reapeat a block of code multiple times.

package Java;

public class ForLoop {
    // Syntax
    // for (initialization; codition; increment/decrement)
    // Code
    public static void main(String [] args){

        for(int i = 1; i <= 5; i++){
            System.out.println(i);
        }
    }
}


/* How it works
   int i =1; - Starts with i = 1
   
   i <= 5; - Continues While i is 5 or less
  
   i++ - Increments i by 1 after each iteration

*/