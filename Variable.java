//Java variable is  a named location in memory used to store data.
package Java;
public class Variable{
    public static void main(String [] args){
        int age = 20; //Data type variable 
        String name = "Jebi"; //Data type variable
        double height = 175.5; // Data type variable
        boolean student = true; // Data type variable

        System.out.println("Name:" + name); // Print the value of the variable
        System.out.println("Age: " + age); // Print the value of the variable
        System.out.println("Height:"+height); // Print the value of the variable
        System.out.println("Student:"+student); // print the value of the variable
    }
}
