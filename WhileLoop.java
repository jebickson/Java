// While loop
// Use a while loop when you don't know in advance how many times the loop will run. 

package Java;

public class WhileLoop {
    // Syntax 
    // while(condition){
    //     Code
    // }

    public static void main(String [] args){

        int i = 1;

        while(i <= 5){
            System.out.println(i);
            i++;
        }
    }
}
