package Java;

// IF-ELSE STATEMENT
// if the condition is true, the if block runs. Otherwise, the else block runs.
 
public class IfElse{
        public static void main(String[] args){

            int age = 16;

            if(age >= 18){
                System.out.println("You are eligible to vote.");
            }

            else{
                System.out.println("You are not eligible to vote.");
            }
        }
}
